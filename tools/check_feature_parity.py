#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Cross-check the two feature extractors — the Python one and the Dart one.

Why it is needed. The model is trained with `ml/features.py` but runs for real
through `mobile/lib/data/recommender/food_vector.dart`. If the two drift by a
single dimension, the model learns in one space and infers in another. **That
defect never reports itself**: the model still runs, still returns scores, the
scores are simply wrong — so it has to be caught by an active check, not by
looking at results.

How it works. The Python side loads every food from the database, builds the
vectors, then writes both the **inputs** and the **expected outputs** into a
JSON fixture. The Dart test reads that file, builds a feature space from the
same set of foods, and compares:

    - the list of food categories and the number of dimensions
    - the six min-max parameters of the normalisation
    - every dimension of every food

The fixture is committed alongside the source, so the Dart test runs without a
database — it only has to be regenerated when the food data changes.

Run:
    python tools/check_feature_parity.py                 # build, then flutter test
    python tools/check_feature_parity.py --fixture-only   # build the fixture only

Note on language: the fixture's keys that the Dart test reads are a contract
with `mobile/test/food_vector_parity_test.dart` and stay exactly as they are.
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ml.db import use_utf8, connect  # noqa: E402
from ml.features import FeatureSpace, load_foods  # noqa: E402

FIXTURE = ROOT / "mobile" / "test" / "fixtures" / "food_vector_parity.json"
DART_TEST = "test/food_vector_parity_test.dart"


def build_fixture() -> tuple[Path, int, int]:
    """Load the foods, build the vectors, write the fixture.

    Returns (path, food count, dimension count).
    """
    cn = connect()
    try:
        foods, report = load_foods(cn)
    finally:
        cn.close()

    report.print_report()

    space = FeatureSpace.from_foods(foods)

    fixture = {
        "_doc": (
            "Generated by tools/check_feature_parity.py — do not edit by hand. "
            "Holds the inputs and the vectors the Python side expects, for the "
            "Dart test to compare dimension by dimension."
        ),
        "feature_version": space.params()["feature_version"],
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "scaler": space.params(),
        "labels": space.labels,
        "length": space.length,
        "foods": [
            {
                "id": f.id,
                "name": f.name,
                "category": f.category,
                "dishRole": f.dish_role,
                "spiceLevel": f.spice_level,
                "kcal": f.kcal,
                "protein": f.protein,
                "carb": f.carb,
                "fat": f.fat,
                "sugar": f.sugar,
                "sodium": f.sodium,
                "fiber": f.fiber,
                "servingSizeG": f.serving_size_g,
                "imputed": list(f.imputed),
            }
            for f in foods
        ],
        "vectors": [space.encode(f) for f in foods],
    }

    FIXTURE.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE.write_text(
        json.dumps(fixture, ensure_ascii=False, indent=1) + "\n",
        encoding="utf-8",
    )
    return FIXTURE, len(foods), space.length


def run_dart_test() -> int:
    flutter = shutil.which("flutter")
    if flutter is None:
        print(
            "\n`flutter` is not on PATH — the fixture was written, run the "
            "Dart part by hand:\n"
            f"    cd mobile && flutter test {DART_TEST}"
        )
        return 0

    print(f"\n$ flutter test {DART_TEST}")
    result = subprocess.run(
        [flutter, "test", DART_TEST],
        cwd=ROOT / "mobile",
        text=True,
    )
    return result.returncode


def main() -> int:
    use_utf8()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--fixture-only",
        action="store_true",
        help="write the fixture only, do not call flutter test",
    )
    args = parser.parse_args()

    path, food_count, dimensions = build_fixture()
    print(
        f"\nWrote {path.relative_to(ROOT)} — "
        f"{food_count} foods x {dimensions} dimensions."
    )

    if args.fixture_only:
        return 0
    return run_dart_test()


if __name__ == "__main__":
    raise SystemExit(main())
