#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Run the ML Service — the four internal endpoints of `API_SPECIFICATION.md` §8.

The counterpart of `tools/run_backend.py`, doing the same three things: wire
`.env` into the process, generate a key if there is none, then start the
server.

If `ML_INTERNAL_KEY` is absent from `.env`, this file GENERATES one and writes
it there. There is deliberately no default key in the source: this is a public
repository, and this service reads the database directly, including the
`users` table.

The backend reads the same variable to set its `X-Internal-Key` header, so the
two match without anyone copying a key by hand.

Run:
    python tools/run_ml_service.py                  # http://localhost:8000
    python tools/run_ml_service.py --reload         # reload on source change
"""

from __future__ import annotations

import argparse
import base64
import os
import pathlib
import secrets
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import _env  # noqa: E402

ENV = ROOT / ".env"
KEY_ENV = "ML_INTERNAL_KEY"


def internal_key() -> str:
    """The shared key between backend and ML Service; generated if absent."""
    existing = _env.get(KEY_ENV, "")
    if existing:
        return existing

    generated = base64.b64encode(secrets.token_bytes(32)).decode()
    with ENV.open("a", encoding="utf-8") as f:
        f.write(
            "\n# Shared key between the backend and the ML Service, sent as "
            "the X-Internal-Key header.\n"
            "# Generated by tools/run_ml_service.py. The backend reads the "
            "same variable.\n"
        )
        f.write(f"{KEY_ENV}={generated}\n")
    print(f"Generated {KEY_ENV} into {ENV.name} (32 bytes, not printed here)")
    return generated


