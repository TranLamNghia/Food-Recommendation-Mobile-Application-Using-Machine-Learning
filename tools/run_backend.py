#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Run the ASP.NET Core backend with `.env` wired into the process.

`dotnet run` does not read `.env`, so without this wrapper the backend starts
with no database password and no signing key, and fails at the first request
rather than at startup.

If `JWT_SIGNING_KEY` is absent from `.env`, this file GENERATES one and writes
it there. There is deliberately no default key in the source: this is a public
repository, and a key committed to a file lets anyone who can read the repo
sign a valid token for any account.

Run:
    python tools/run_backend.py            # http://localhost:5000/api/v1
    python tools/run_backend.py --build    # compile only
"""

from __future__ import annotations

import argparse
import base64
import os
import pathlib
import secrets
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import _env  # noqa: E402

PROJECT = ROOT / "backend" / "Api"
ENV = ROOT / ".env"


def signing_key() -> str:
    """The JWT signing key, generated into `.env` if it is not there yet."""
    existing = _env.get("JWT_SIGNING_KEY", "")
    if existing:
        return existing

    generated = base64.b64encode(secrets.token_bytes(48)).decode()
    with ENV.open("a", encoding="utf-8") as f:
        f.write(
            "\n# JWT signing key (HMAC-SHA256). Generated by "
            "tools/run_backend.py.\n"
            "# Changing it invalidates every accessToken currently alive.\n"
        )
        f.write(f"JWT_SIGNING_KEY={generated}\n")
    print(
        f"Generated JWT_SIGNING_KEY into {ENV.name} "
        "(48 bytes, not printed here)"
    )
    return generated


def main(argv: list[str] | None = None) -> int:
    _env.use_utf8()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--build", action="store_true", help="only `dotnet build`, do not run"
    )
    parser.add_argument(
        "--urls",
        default="http://localhost:5000",
        help="the address to listen on; defaults to the one in spec section 2.1",
    )
    args = parser.parse_args(argv)

    environ = dict(os.environ)
    environ["JWT_SIGNING_KEY"] = signing_key()
    for name in (
        "MYSQL_HOST",
        "MYSQL_PORT",
        "MYSQL_USER",
        "MYSQL_PASSWORD",
        "MYSQL_DATABASE",
        # The ML service, per specification section 8. Absent, the backend
        # still starts -- that is deliberate, see MlOptions -- but every
        # recommendation answers 503 ML_UNAVAILABLE, so forgetting to pass
        # these two is indistinguishable from the ML service being down.
        "ML_INTERNAL_KEY",
        "ML_SERVICE_URL",
        # Password reset mail, specification 7.1.5. With no SMTP_HOST the
        # mails are written into MAIL_OUTBOX_DIR instead of being sent.
        "SMTP_HOST",
        "SMTP_PORT",
        "SMTP_USER",
        "SMTP_PASSWORD",
        "SMTP_SSL",
        "MAIL_FROM",
        "MAIL_OUTBOX_DIR",
    ):
        value = _env.get(name, "")
        if value:
            environ[name] = value

    # One outbox for the backend and tools/smoke_backend.py, which reads the
    # reset code back out of it. At the repository root rather than under
    # backend/Api, where `dotnet run` would otherwise put it.
    environ.setdefault("MAIL_OUTBOX_DIR", str(ROOT / ".mail-outbox"))

    missing = [n for n in ("MYSQL_USER", "MYSQL_PASSWORD") if not environ.get(n)]
    if missing:
        print(f"Missing {', '.join(missing)} in .env", file=sys.stderr)
        return 1

    if args.build:
        command = ["dotnet", "build", str(PROJECT)]
    else:
        command = ["dotnet", "run", "--project", str(PROJECT), "--urls", args.urls]
        print(
            f"Backend: {args.urls}/api/v1   "
            f"(database {environ.get('MYSQL_DATABASE', 'nutrition_rec')})"
        )
        if not environ.get("ML_INTERNAL_KEY"):
            print(
                "ML_INTERNAL_KEY is not in .env, so the ML service will "
                "not be called and every recommendation will answer 503 "
                "ML_UNAVAILABLE."
                "\nStart the service with:\n"
                "    python tools/run_ml_service.py",
                file=sys.stderr,
            )

    return subprocess.call(command, env=environ, cwd=str(ROOT))


if __name__ == "__main__":
    raise SystemExit(main())
