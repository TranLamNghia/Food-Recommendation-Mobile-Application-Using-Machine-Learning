#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Run the ASP.NET Core backend with `.env` wired into the process.

`dotnet run` does not read `.env`, so without this wrapper the backend starts
with no database password and no signing key, and fails at the first request
rather than at startup.

If `JWT_SIGNING_KEY` is absent from `.env`, this file GENERATES one and writes
it there. There is deliberately no default key in the source: this is a public
repository, and a key committed to a file lets anyone who can read the repo
sign a valid token for any account.

Run:
    python tools/run_backend.py            # http://localhost:5000/api/v1
    python tools/run_backend.py --build    # compile only
"""

from __future__ import annotations

import argparse
import base64
import os
import pathlib
import secrets
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import _env  # noqa: E402

PROJECT = ROOT / "backend" / "Api"
ENV = ROOT / ".env"


def signing_key() -> str:
    """The JWT signing key, generated into `.env` if it is not there yet."""
    existing = _env.get("JWT_SIGNING_KEY", "")
    if existing:
        return existing

    generated = base64.b64encode(secrets.token_bytes(48)).decode()
    with ENV.open("a", encoding="utf-8") as f:
        f.write(
            "\n# JWT signing key (HMAC-SHA256). Generated by "
            "tools/run_backend.py.\n"
            "# Changing it invalidates every accessToken currently alive.\n"
        )
        f.write(f"JWT_SIGNING_KEY={generated}\n")
    print(
        f"Generated JWT_SIGNING_KEY into {ENV.name} "
        "(48 bytes, not printed here)"
    )
    return generated


def main(argv: list[str] | None = None) -> int:
    _env.use_utf8()
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--build", action="store_true", help="only `dotnet build`, do not run"
    )
    parser.add_argument(
        "--urls",
        default="http://localhost:5000",
        help="the address to listen on; defaults to the one in spec section 2.1",
    )
    args = parser.parse_args(argv)

    environ = dict(os.environ)
    environ["JWT_SIGNING_KEY"] = signing_key()
